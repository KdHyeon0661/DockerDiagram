    [Fact]
    public void UserDataProtectionRoundTripsWithoutLeavingPlaintext()
    {
        const string secret = "DATABASE_PASSWORD=correct-horse-battery-staple";

        string protectedValue = UserDataProtection.Protect(secret);

        Assert.StartsWith(UserDataProtection.Prefix, protectedValue);
        Assert.DoesNotContain("correct-horse-battery-staple", protectedValue, StringComparison.Ordinal);
        Assert.Equal(secret, UserDataProtection.Unprotect(protectedValue));
    }

    [Fact]
    public void UserDataProtectionLoadsLegacyPlaintext()
    {
        const string legacyValue = "PLAIN_VALUE=legacy";

        Assert.Equal(legacyValue, UserDataProtection.Unprotect(legacyValue));
    }

    [Fact]
    public async Task SaveAndLoadProtectsSensitiveFieldsAndRestoresTheirValues()
    {
        string directory = CreateTestDirectory();
        string path = Path.Combine(directory, "protected.vdm");
        string previousLastPath = DockerDiagram.Properties.Settings.Default.LastFilePath;
        using IDockerService dockerService = DispatchProxy.Create<IDockerService, TrackingDockerServiceProxy>();
        IDialogService dialogService = DispatchProxy.Create<IDialogService, LenientDialogServiceProxy>();
        using var factory = new DockerServiceFactory(_ =>
            DispatchProxy.Create<IDockerService, TrackingDockerServiceProxy>());
        using var main = new MainViewModel(dockerService, dialogService, factory);
        SheetViewModel sheet = main.ActiveSheet!;
        sheet.ComposeRawYaml = "services:\n  api:\n    environment:\n      API_TOKEN: compose-secret";
        sheet.Nodes.Add(new NodeViewModel(dockerService, dockerService, dialogService)
        {
            Type = NodeType.Container,
            Name = "api",
            EnvironmentVariables = new List<string> { "API_TOKEN=environment-secret" },
            ComposeRawServiceYaml = "environment:\n  API_TOKEN: service-secret",
            ComposeRawVolumeYaml = "driver_opts:\n  password: volume-secret"
        });
        sheet.Groups.Add(new GroupViewModel(0, 0, 300, 200, dockerService, dialogService, "backend", GroupType.Network)
        {
            ParentSheet = sheet,
            ComposeRawNetworkYaml = "driver_opts:\n  password: network-secret"
        });

        try
        {
            DiagramSaveResult saveResult = FileService.QuickSaveWithResult(main, path);
            Assert.True(saveResult.Success, saveResult.ErrorMessage);

            string savedJson = File.ReadAllText(path);
            Assert.Contains(UserDataProtection.Prefix, savedJson, StringComparison.Ordinal);
            Assert.DoesNotContain("compose-secret", savedJson, StringComparison.Ordinal);
            Assert.DoesNotContain("environment-secret", savedJson, StringComparison.Ordinal);
            Assert.DoesNotContain("service-secret", savedJson, StringComparison.Ordinal);
            Assert.DoesNotContain("volume-secret", savedJson, StringComparison.Ordinal);
            Assert.DoesNotContain("network-secret", savedJson, StringComparison.Ordinal);

            bool loaded = await FileService.LoadDiagramFromPathAsync(
                main,
                path,
                dockerService,
                dockerService,
                dockerService,
                dialogService);

            Assert.True(loaded);
            Assert.Contains("compose-secret", main.ActiveSheet!.ComposeRawYaml, StringComparison.Ordinal);
            NodeViewModel restoredNode = Assert.Single(main.ActiveSheet.Nodes);
            Assert.Contains("API_TOKEN=environment-secret", restoredNode.EnvironmentVariables);
            Assert.Contains("service-secret", restoredNode.ComposeRawServiceYaml, StringComparison.Ordinal);
            Assert.Contains("volume-secret", restoredNode.ComposeRawVolumeYaml, StringComparison.Ordinal);
            Assert.Contains("network-secret", Assert.Single(main.ActiveSheet.Groups).ComposeRawNetworkYaml, StringComparison.Ordinal);
        }
        finally
        {
            DockerDiagram.Properties.Settings.Default.LastFilePath = previousLastPath;
            DockerDiagram.Properties.Settings.Default.Save();
            Directory.Delete(directory, recursive: true);
        }
    }

