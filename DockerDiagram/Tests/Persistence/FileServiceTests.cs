        {
            bool loaded = await FileService.LoadDiagramFromPathAsync(
                main,
                path,
                dockerService,
                dockerService,
                dockerService,
                dialogService);

            Assert.True(loaded);
            NodeViewModel hostPath = Assert.Single(main.ActiveSheet!.Nodes, node => node.Type == NodeType.HostPath);
            NodeViewModel container = Assert.Single(main.ActiveSheet.Nodes, node => node.Type == NodeType.Container);
            Assert.Equal("C:\\host\\data", hostPath.HostPath);
            ConnectorViewModel connector = Assert.Single(main.ActiveSheet.Connectors);
            Assert.Equal(MountKind.Bind, connector.MountKind);
            ContainerMountSpec mount = Assert.Single(container.MountSpecifications);
            Assert.Equal(MountKind.Bind, mount.Kind);
            Assert.Equal("C:\\host\\data", mount.Source);
            Assert.Equal("/data", mount.Target);
        }
        finally
        {
            Directory.Delete(directory, recursive: true);
        }
    }

