public class UnexpectedDialogServiceProxy : DispatchProxy
{
    protected override object? Invoke(MethodInfo? targetMethod, object?[]? args) =>
        throw new NotSupportedException($"Unexpected dialog service call: {targetMethod?.Name}");
}

public class LenientDialogServiceProxy : DispatchProxy
{
    protected override object? Invoke(MethodInfo? targetMethod, object?[]? args)
    {
        Type returnType = targetMethod?.ReturnType ?? typeof(void);
        if (returnType == typeof(void)) return null;
        if (returnType == typeof(bool)) return true;
        if (returnType == typeof(DialogChoice)) return DialogChoice.Cancel;
        if (returnType == typeof(Task)) return Task.CompletedTask;
        if (returnType.IsGenericType && returnType.GetGenericTypeDefinition() == typeof(Task<>))
        {
            Type valueType = returnType.GetGenericArguments()[0];
            object? value = valueType.IsValueType ? Activator.CreateInstance(valueType) : null;
            return typeof(Task).GetMethod(nameof(Task.FromResult))!
                .MakeGenericMethod(valueType)
                .Invoke(null, new[] { value });
        }
        return returnType.IsValueType ? Activator.CreateInstance(returnType) : null;
    }
}
