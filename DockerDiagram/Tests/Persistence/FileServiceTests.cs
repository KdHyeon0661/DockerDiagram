    [Fact]
    public void CurrentFormatRoundTripsExplicitMountTypesAndConnectorMetadata()
    {
        var file = new DiagramFile
        {
            Sheets =
            {
                new SheetData
                {
                    Nodes =
                    {
                        new NodeData
                        {
                            Id = "container",
                            Type = NodeType.Container,
                            MountSpecifications =
                            [
                                new ContainerMountSpec
                                {
                                    Kind = MountKind.Bind,
                                    Source = "C:\\host\\data",
                                    Target = "/data",
                                    ReadOnly = true,
                                    BindPropagation = "rshared"
                                },
                                new ContainerMountSpec
                                {
                                    Kind = MountKind.Tmpfs,
                                    Target = "/run/cache",
                                    TmpfsSizeBytes = 4096,
                                    TmpfsMode = Convert.ToUInt32("1750", 8)
                                }
                            ]
                        }
                    },
                    Connections =
                    {
                        new ConnectionData
                        {
                            SourceNodeId = "container",
                            TargetNodeId = "host-path",
                            RelationType = RelationType.VolumeMount,
                            MountPath = "/data",
                            MountKind = MountKind.Bind,
                            MountReadOnly = true,
                            MountOptions = "ro · rshared"
                        }
                    }
                }
            }
        };

        string json = JsonSerializer.Serialize(file);
        DiagramFile? restored = JsonSerializer.Deserialize<DiagramFile>(json);

        Assert.DoesNotContain("KindLabel", json, StringComparison.Ordinal);
        Assert.DoesNotContain("OptionSummary", json, StringComparison.Ordinal);
        Assert.Equal(MountKind.Bind, restored!.Sheets[0].Nodes[0].MountSpecifications[0].Kind);
        Assert.Equal(MountKind.Tmpfs, restored.Sheets[0].Nodes[0].MountSpecifications[1].Kind);
        Assert.Equal(4096, restored.Sheets[0].Nodes[0].MountSpecifications[1].TmpfsSizeBytes);
        Assert.Equal(MountKind.Bind, restored.Sheets[0].Connections[0].MountKind);
        Assert.True(restored.Sheets[0].Connections[0].MountReadOnly);
    }

